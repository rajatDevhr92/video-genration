    @staticmethod
    def build_scene_state(
        scene,
        previous_state=None,
    ):
        """
        Build explicit continuity state for the current scene.

        State is intentionally derived from the story plan and
        previous scene state. It does not invent persistent objects.
        """
        previous_state = previous_state or {}

        state = {
            "scene_id": scene.get("id"),
            "order": scene.get("order"),
            "location": scene.get(
                "location_id"
            ),
            "characters": list(
                scene.get(
                    "character_ids",
                    []
                )
            ),
            "weather": scene.get(
                "weather"
            ),
            "lighting": scene.get(
                "lighting"
            ),
            "objects": dict(
                previous_state.get(
                    "objects",
                    {}
                )
            ),
            "notes": list(
                previous_state.get(
                    "notes",
                    []
                )
            ),
        }

        # Optional continuity section generated by the planner.
        continuity = scene.get(
            "continuity"
        )

        if isinstance(continuity, dict):

            persistent_objects = continuity.get(
                "persistent_objects",
                []
            )

            if isinstance(
                persistent_objects,
                list,
            ):
                for obj in persistent_objects:

                    if not isinstance(
                        obj,
                        dict,
                    ):
                        continue

                    obj_id = obj.get("id")

                    if obj_id:
                        state["objects"][obj_id] = obj

            continuity_notes = continuity.get(
                "notes",
                []
            )

            if isinstance(
                continuity_notes,
                list,
            ):
                state["notes"].extend(
                    continuity_notes
                )

            elif continuity_notes:
                state["notes"].append(
                    continuity_notes
                )

        return state

